CREATE TABLE payment_attempt (
    id VARCHAR(64) NOT NULL PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    payment_id VARCHAR(64) NOT NULL,
    attempt_no INT NOT NULL,
    amount_minor BIGINT NOT NULL,
    currency CHAR(3) NOT NULL,
    binding_revision_id VARCHAR(64) NOT NULL,
    channel VARCHAR(24) NOT NULL,
    access_mode VARCHAR(24) NOT NULL,
    account_scope_hash CHAR(64) NOT NULL,
    method VARCHAR(24) NOT NULL,
    channel_request_no VARCHAR(32) NOT NULL,
    state VARCHAR(24) NOT NULL,
    execution_epoch BIGINT NOT NULL DEFAULT 0,
    no_collection_evidence_id VARCHAR(64) NULL,
    limit_operation_id VARCHAR(64) NOT NULL,
    caller_service_id VARCHAR(64) NOT NULL,
    request_key VARCHAR(128) NOT NULL,
    request_digest CHAR(64) NOT NULL,
    payment_request_digest CHAR(64) NOT NULL,
    prepared_input_ref VARCHAR(64) NULL,
    risk_decision VARCHAR(24) NULL,
    risk_reason VARCHAR(64) NULL,
    risk_consultation_ref VARCHAR(128) NULL,
    execution_permit_hash CHAR(64) NULL,
    prepared_at DATETIME(6) NOT NULL,
    submission_started_at DATETIME(6) NULL,
    row_version BIGINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_attempt_no (tenant_id, payment_id, attempt_no),
    UNIQUE KEY uk_attempt_action (tenant_id, payment_id, request_key),
    UNIQUE KEY uk_attempt_channel_request (channel, account_scope_hash, channel_request_no),
    KEY ix_attempt_recovery (tenant_id, state, updated_at, id),
    CHECK (attempt_no > 0 AND amount_minor > 0 AND currency = 'CNY' AND row_version >= 0),
    CHECK (method IN ('PAYMENT_CODE','JSAPI','H5')),
    CHECK (state IN ('INIT','SUBMITTING','PENDING','UNKNOWN','SUCCEEDED','FAILED','CLOSED')),
    CHECK ((execution_epoch = 0 AND execution_permit_hash IS NULL AND submission_started_at IS NULL AND state IN ('INIT','CLOSED'))
        OR (execution_epoch > 0 AND execution_permit_hash IS NOT NULL AND submission_started_at IS NOT NULL
            AND submission_started_at >= prepared_at AND risk_decision IN ('DEFAULT_ALLOW','ALLOW') AND risk_reason IS NOT NULL)),
    CHECK (state <> 'INIT' OR (risk_decision IS NULL AND risk_reason IS NULL AND risk_consultation_ref IS NULL AND row_version = 0)),
    CHECK (state NOT IN ('FAILED','CLOSED') OR no_collection_evidence_id IS NOT NULL),
    CHECK (state <> 'CLOSED' OR row_version > 0),
    CHECK ((risk_decision IS NULL AND risk_reason IS NULL AND risk_consultation_ref IS NULL)
        OR (risk_decision IN ('DEFAULT_ALLOW','ALLOW','DENY') AND risk_reason IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
