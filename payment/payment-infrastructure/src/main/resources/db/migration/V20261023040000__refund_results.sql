CREATE TABLE refund_channel_receipt (
    id VARCHAR(64) NOT NULL PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    refund_id VARCHAR(64) NOT NULL,
    source VARCHAR(24) NOT NULL,
    receipt_key VARCHAR(128) NOT NULL,
    facts_digest CHAR(64) NOT NULL,
    source_digest CHAR(64) NOT NULL,
    observation_payload LONGTEXT NOT NULL,
    disposition VARCHAR(24) NOT NULL,
    reason_code VARCHAR(64) NULL,
    received_at DATETIME(6) NOT NULL,
    UNIQUE KEY uk_refund_channel_receipt (tenant_id, refund_id, source, receipt_key),
    CHECK (deleted = 0 AND source IN ('SUBMIT_RESPONSE', 'QUERY_RESPONSE', 'CALLBACK')),
    CHECK (JSON_VALID(observation_payload) AND OCTET_LENGTH(observation_payload) <= 32768),
    CHECK (disposition IN ('APPLIED', 'IGNORED', 'CONFLICT')),
    CHECK (disposition <> 'CONFLICT' OR reason_code IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE refund_result_anomaly (
    id VARCHAR(64) NOT NULL PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    refund_id VARCHAR(64) NOT NULL,
    receipt_id VARCHAR(64) NOT NULL,
    reason_code VARCHAR(64) NOT NULL,
    facts_digest CHAR(64) NOT NULL,
    observation_payload LONGTEXT NOT NULL,
    received_at DATETIME(6) NOT NULL,
    UNIQUE KEY uk_refund_result_anomaly (tenant_id, receipt_id, facts_digest, reason_code),
    KEY ix_refund_anomaly (tenant_id, refund_id, received_at, id),
    CHECK (deleted = 0 AND JSON_VALID(observation_payload) AND OCTET_LENGTH(observation_payload) <= 32768)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE refund_transaction_claim (
    id VARCHAR(64) NOT NULL PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    refund_id VARCHAR(64) NOT NULL,
    payment_id VARCHAR(64) NOT NULL,
    attempt_id VARCHAR(64) NOT NULL,
    channel VARCHAR(24) NOT NULL,
    binding_revision_id VARCHAR(64) NOT NULL,
    account_scope_hash CHAR(64) NOT NULL,
    channel_request_no VARCHAR(64) NOT NULL,
    original_channel_transaction_no VARCHAR(128) NOT NULL,
    channel_refund_no VARCHAR(64) NOT NULL,
    amount_minor BIGINT NOT NULL,
    currency CHAR(3) NOT NULL,
    channel_refund_transaction_no VARCHAR(128) NOT NULL,
    succeeded_at DATETIME(6) NOT NULL,
    receipt_id VARCHAR(64) NOT NULL,
    UNIQUE KEY uk_refund_transaction (channel, account_scope_hash, channel_refund_transaction_no),
    UNIQUE KEY uk_refund_claim_child (tenant_id, refund_id),
    CHECK (deleted = 0 AND amount_minor > 0 AND currency = 'CNY')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
