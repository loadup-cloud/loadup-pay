-- Sensitive input ciphertext is isolated from payment intents and scoped to one fixed payment.
CREATE TABLE payment_input (
    id VARCHAR(64) NOT NULL,
    tenant_id VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    payment_id VARCHAR(64) NOT NULL,
    order_id VARCHAR(64) NOT NULL,
    allocation_id VARCHAR(64) NOT NULL,
    payee_merchant_id VARCHAR(64) NOT NULL,
    amount_minor BIGINT NOT NULL,
    currency CHAR(3) NOT NULL,
    input_key VARCHAR(128) NOT NULL,
    channel VARCHAR(24) NOT NULL,
    method VARCHAR(24) NOT NULL,
    caller_service_id VARCHAR(64) NOT NULL,
    fingerprint_key_id VARCHAR(64) NOT NULL,
    input_digest CHAR(64) NOT NULL,
    encryption_key VARCHAR(128) NOT NULL,
    encryption_version INT NOT NULL,
    ciphertext TEXT NOT NULL,
    prepared_at DATETIME(6) NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    state VARCHAR(24) NOT NULL,
    bound_attempt_id VARCHAR(64) NULL,
    row_version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_input_payment (tenant_id, payment_id),
    KEY ix_input_expiry (tenant_id, expires_at, id),
    CHECK (amount_minor > 0 AND currency = 'CNY'),
    CHECK (method IN ('PAYMENT_CODE', 'JSAPI')),
    CHECK (expires_at > prepared_at AND encryption_version > 0),
    CHECK ((state = 'INIT' AND bound_attempt_id IS NULL AND row_version = 0)
        OR (state = 'BOUND' AND bound_attempt_id IS NOT NULL AND row_version = 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
