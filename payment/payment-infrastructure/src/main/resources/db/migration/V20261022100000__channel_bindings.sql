-- Immutable account identities, mutable routing heads and durable management operation receipts.
CREATE TABLE channel_merchant_binding (
    id VARCHAR(64) NOT NULL PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    payee_merchant_id VARCHAR(64) NOT NULL,
    binding_code VARCHAR(64) NOT NULL,
    channel VARCHAR(24) NOT NULL,
    access_mode VARCHAR(24) NOT NULL,
    state VARCHAR(24) NOT NULL,
    current_revision_id VARCHAR(64) NOT NULL,
    current_revision INT NOT NULL,
    priority INT NOT NULL,
    row_version BIGINT NOT NULL,
    UNIQUE KEY uk_binding_code (tenant_id, payee_merchant_id, binding_code),
    KEY ix_binding_route (tenant_id, payee_merchant_id, channel, access_mode, state, id),
    CHECK (channel IN ('ALIPAY','WECHAT')),
    CHECK (access_mode IN ('DIRECT','SERVICE_PROVIDER')),
    CHECK (state IN ('ACTIVE','SUSPENDED','REVOKED')),
    CHECK (current_revision > 0 AND row_version > 0 AND priority BETWEEN 0 AND 1000000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE channel_binding_revision (
    id VARCHAR(64) NOT NULL PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    binding_id VARCHAR(64) NOT NULL,
    revision INT NOT NULL,
    payee_merchant_id VARCHAR(64) NOT NULL,
    channel VARCHAR(24) NOT NULL,
    access_mode VARCHAR(24) NOT NULL,
    account_scope_hash CHAR(64) NOT NULL,
    credential_reference VARCHAR(128) NOT NULL,
    credential_version VARCHAR(64) NOT NULL,
    identity_payload JSON NOT NULL,
    identity_hash CHAR(64) NOT NULL,
    payment_code_enabled TINYINT NOT NULL,
    jsapi_enabled TINYINT NOT NULL,
    h5_enabled TINYINT NOT NULL,
    caller_service_id VARCHAR(64) NOT NULL,
    published_at DATETIME(6) NOT NULL,
    UNIQUE KEY uk_binding_revision (tenant_id, binding_id, revision),
    CHECK (revision > 0 AND channel IN ('ALIPAY','WECHAT')),
    CHECK (access_mode IN ('DIRECT','SERVICE_PROVIDER')),
    CHECK (payment_code_enabled IN (0,1) AND jsapi_enabled IN (0,1) AND h5_enabled IN (0,1)),
    CHECK (payment_code_enabled + jsapi_enabled + h5_enabled > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE channel_binding_change_receipt (
    id VARCHAR(64) NOT NULL PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    binding_id VARCHAR(64) NOT NULL,
    kind VARCHAR(24) NOT NULL,
    request_key VARCHAR(128) NOT NULL,
    request_digest CHAR(64) NOT NULL,
    caller_service_id VARCHAR(64) NOT NULL,
    binding_revision_id VARCHAR(64) NOT NULL,
    revision INT NOT NULL,
    state VARCHAR(24) NOT NULL,
    applied_version BIGINT NOT NULL,
    applied_at DATETIME(6) NOT NULL,
    UNIQUE KEY uk_binding_change (tenant_id, binding_id, request_key),
    CHECK ((kind = 'PUBLISH' AND state = 'ACTIVE') OR (kind = 'SUSPEND' AND state = 'SUSPENDED')
        OR (kind = 'REVOKE' AND state = 'REVOKED')),
    CHECK (revision > 0 AND applied_version > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
