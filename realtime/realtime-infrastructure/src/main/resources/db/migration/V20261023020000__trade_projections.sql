-- Independent eventual read models. Payloads are complete typed source snapshots, not financial authority.
CREATE TABLE trade_order_projection (
    id VARCHAR(64) NOT NULL PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    order_id VARCHAR(64) NOT NULL,
    payee_merchant_id VARCHAR(64) NOT NULL,
    merchant_order_no VARCHAR(64) NOT NULL,
    state VARCHAR(24) NOT NULL,
    business_created_at DATETIME(6) NOT NULL,
    source_version BIGINT NOT NULL,
    content_hash CHAR(64) NOT NULL,
    payload LONGTEXT NOT NULL,
    snapshot_at DATETIME(6) NOT NULL,
    UNIQUE KEY uk_order (tenant_id, order_id),
    KEY ix_order_page (tenant_id, payee_merchant_id, business_created_at, order_id),
    UNIQUE KEY uk_merchant_order (tenant_id, payee_merchant_id, merchant_order_no),
    CHECK (deleted = 0 AND source_version >= 0),
    CHECK (JSON_VALID(payload) AND OCTET_LENGTH(payload) <= 1048576)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

