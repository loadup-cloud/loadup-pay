CREATE TABLE trade_projection_receipt (
    id VARCHAR(64) NOT NULL PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    delivery_id VARCHAR(64) NOT NULL,
    business_event_id VARCHAR(64) NOT NULL,
    producer VARCHAR(32) NOT NULL,
    aggregate_id VARCHAR(64) NOT NULL,
    source_version BIGINT NOT NULL,
    projected_version BIGINT NOT NULL,
    disposition VARCHAR(24) NOT NULL,
    request_digest CHAR(64) NOT NULL,
    caller_service_id VARCHAR(64) NOT NULL,
    accepted_at DATETIME(6) NOT NULL,
    UNIQUE KEY uk_projection_delivery (tenant_id, producer, delivery_id),
    KEY ix_projection_source (tenant_id, producer, aggregate_id, source_version),
    CHECK (deleted = 0 AND source_version >= 0 AND projected_version >= source_version),
    CHECK (disposition IN ('APPLIED','DUPLICATE','STALE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
