#!/usr/bin/env python3
"""Materialise framework component schemas into each application-owned Flyway history.

Components publish DDL as `db/schema/<name>.sql` templates. Flyway never scans
dependency JARs; every application owns one ordered migration history under
`src/main/resources/db/migration`. Run this script after changing a component
schema or an application's component dependencies.

Usage:
    python3 scripts/gen-migrations.py          # write missing/updated files
    python3 scripts/gen-migrations.py --check  # fail when the tree is stale
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

PAY_ROOT = Path(__file__).resolve().parent.parent
FRAMEWORK_ROOT = Path(os.environ.get("LOADUP_FRAMEWORK_ROOT", PAY_ROOT.parent / "loadup-framework")).resolve()

# Application migration directories. The versions below stay before every
# application-owned migration so shared infrastructure tables exist first.
APP_DIRS = {
    "acquire": "acquire/acquire-infrastructure/src/main/resources/db/migration",
    "payment": "payment/payment-infrastructure/src/main/resources/db/migration",
    "reconciliation": "reconciliation/reconciliation-infrastructure/src/main/resources/db/migration",
    "merchantcenter": "merchantcenter/merchantcenter-service/src/main/resources/db/migration",
    "productcenter": "productcenter/productcenter-infrastructure/src/main/resources/db/migration",
    "notificationcenter": "notificationcenter/notificationcenter-bootstrap/src/main/resources/db/migration",
    "limitcenter": "limitcenter/limitcenter-infrastructure/src/main/resources/db/migration",
    "realtime": "realtime/realtime-service/src/main/resources/db/migration",
}

SCHEMAS = {
    "outbox": (
        "20260101000001",
        "loadup-components/reliability/loadup-components-outbox/src/main/resources/db/schema/outbox.sql",
    ),
    "delayed_task": (
        "20260101000002",
        "loadup-components/reliability/loadup-components-delayedtask/src/main/resources/db/schema/delayed_task.sql",
    ),
    "global_unique": (
        "20260101000003",
        "loadup-components/reliability/loadup-components-globalunique/src/main/resources/db/schema/global_unique.sql",
    ),
    "gotone_store": (
        "20260101000004",
        "loadup-components/integration/loadup-components-gotone/loadup-components-gotone-store-jdbc/src/main/resources/db/schema/gotone_store.sql",
    ),
    "sequence_allocation": (
        "20260101000005",
        "loadup-components/data/loadup-components-database/src/main/resources/db/schema/sequence_allocation.sql",
    ),
    "file_storage": (
        "20260101000006",
        "loadup-components/data/loadup-components-dfs/loadup-components-dfs-binder-database/src/main/resources/db/schema/file_storage.sql",
    ),
}

# Reviewable per-application component usage. Add an entry when an application
# starts using a component that owns tables.
APP_SCHEMAS = {
    "acquire": ["outbox", "delayed_task", "sequence_allocation"],
    "payment": ["outbox", "delayed_task", "sequence_allocation"],
    "reconciliation": ["outbox", "delayed_task", "sequence_allocation"],
    "merchantcenter": ["global_unique", "sequence_allocation"],
    "productcenter": ["outbox", "sequence_allocation"],
    "notificationcenter": ["gotone_store"],
    "limitcenter": ["sequence_allocation"],
    "realtime": ["sequence_allocation"],
}

HEADER = "-- Generated by scripts/gen-migrations.py from a framework db/schema template.\n"


def target_text(schema: str) -> str:
    version, relative = SCHEMAS[schema]
    source = FRAMEWORK_ROOT / relative
    if not source.is_file():
        raise SystemExit(f"Missing component schema template: {source}")
    return f"{HEADER}{source.read_text(encoding='utf-8').rstrip()}\n"


def target_name(schema: str) -> str:
    version, _ = SCHEMAS[schema]
    return f"V{version}__{schema}.sql"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale: list[Path] = []
    for app, schemas in APP_SCHEMAS.items():
        directory = PAY_ROOT / APP_DIRS[app]
        directory.mkdir(parents=True, exist_ok=True)
        expected = {target_name(schema): target_text(schema) for schema in schemas}
        for name, content in expected.items():
            path = directory / name
            current = path.read_text(encoding="utf-8") if path.is_file() else None
            if current != content:
                stale.append(path)
                if not check:
                    path.write_text(content, encoding="utf-8")
        for existing in directory.glob("V202601010000*__*.sql"):
            if existing.name not in expected:
                stale.append(existing)
                if not check:
                    existing.unlink()
    if check:
        if stale:
            for path in stale:
                print(f"stale: {path}", file=sys.stderr)
            return 1
        print("Component migrations are in sync.")
        return 0
    print(f"Generated {len(stale)} component migration file(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
