#!/usr/bin/env python3
"""Create missing component snapshots without rewriting application migration history.

Applications explicitly select db/migration/pay/<app> and approved framework
module namespaces. Existing snapshots are frozen by component-migrations.lock.json;
template changes require new, reviewed versioned migrations instead of regeneration.

Usage:
    python3 scripts/gen-migrations.py          # create missing initial snapshots
    python3 scripts/gen-migrations.py --check  # validate snapshots without writing
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

PAY_ROOT = Path(__file__).resolve().parent.parent
FRAMEWORK_ROOT = Path(os.environ.get("LOADUP_FRAMEWORK_ROOT", PAY_ROOT.parent / "loadup-framework")).resolve()
LOCK_PATH = PAY_ROOT / "scripts/component-migrations.lock.json"

# Application migration directories. The versions below stay before every
# application-owned migration so shared infrastructure tables exist first.
APP_DIRS = {
    "acquire": "acquire/acquire-infrastructure/src/main/resources/db/migration/pay/acquire",
    "payment": "payment/payment-infrastructure/src/main/resources/db/migration/pay/payment",
    "reconciliation": "reconciliation/reconciliation-infrastructure/src/main/resources/db/migration/pay/reconciliation",
    "merchantcenter": "merchantcenter/merchantcenter-service/src/main/resources/db/migration/pay/merchantcenter",
    "productcenter": "productcenter/productcenter-infrastructure/src/main/resources/db/migration/pay/productcenter",
    "notificationcenter": "notificationcenter/notificationcenter-bootstrap/src/main/resources/db/migration/pay/notificationcenter",
    "limitcenter": "limitcenter/limitcenter-infrastructure/src/main/resources/db/migration/pay/limitcenter",
    "realtime": "realtime/realtime-service/src/main/resources/db/migration/pay/realtime",
    "admin": "admin/admin-bootstrap/src/main/resources/db/migration/pay/admin",
}

SCHEMAS = {
    "outbox": (
        "20260101000001",
        "loadup-components/reliability/loadup-components-outbox/src/main/resources/db/schema/outbox.sql",
    ),
    "delayed_task": (
        "20260101000002",
        "loadup-components/reliability/loadup-components-delayedtask/src/main/resources/db/schema/delayed_task.sql",
    ),
    "global_unique": (
        "20260101000003",
        "loadup-components/reliability/loadup-components-globalunique/src/main/resources/db/schema/global_unique.sql",
    ),
    "gotone_store": (
        "20260101000004",
        "loadup-components/integration/loadup-components-gotone/loadup-components-gotone-store-jdbc/src/main/resources/db/schema/gotone_store.sql",
    ),
    "sequence_allocation": (
        "20260101000005",
        "loadup-components/data/loadup-components-database/src/main/resources/db/schema/sequence_allocation.sql",
    ),
    "file_storage": (
        "20260101000006",
        "loadup-components/data/loadup-components-dfs/loadup-components-dfs-binder-database/src/main/resources/db/schema/file_storage.sql",
    ),
}

# Reviewable per-application component usage. Add an entry when an application
# starts using a component that owns tables.
APP_SCHEMAS = {
    "acquire": ["outbox", "delayed_task", "sequence_allocation"],
    "payment": ["outbox", "delayed_task", "sequence_allocation"],
    "reconciliation": ["outbox", "delayed_task", "sequence_allocation"],
    "merchantcenter": ["global_unique", "sequence_allocation"],
    "productcenter": ["outbox", "sequence_allocation"],
    "notificationcenter": ["gotone_store"],
    "limitcenter": ["sequence_allocation"],
    "realtime": ["sequence_allocation"],
    "admin": ["sequence_allocation"],
}

HEADER = "-- Generated by scripts/gen-migrations.py from a framework db/schema template.\n"


def target_text(schema: str) -> str:
    version, relative = SCHEMAS[schema]
    source = FRAMEWORK_ROOT / relative
    if not source.is_file():
        raise SystemExit(f"Missing component schema template: {source}")
    return f"{HEADER}{source.read_text(encoding='utf-8').rstrip()}\n"


def target_name(schema: str) -> str:
    version, _ = SCHEMAS[schema]
    return f"V{version}__{schema}.sql"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify frozen snapshots; write nothing")
    args = parser.parse_args(argv)
    try:
        lock = json.loads(LOCK_PATH.read_text(encoding="utf-8"))
        if lock.get("format") != 1 or not isinstance(lock.get("files"), dict):
            raise ValueError("Invalid component migration lock file")
        frozen = lock["files"]
        # Validate every historical snapshot, even after a dependency is removed.
        # Complete the preflight before creating any new file.
        for relative, entry in frozen.items():
            path = (PAY_ROOT / relative).resolve()
            if not path.is_relative_to(PAY_ROOT.resolve()):
                raise ValueError(f"Snapshot is outside the repository: {relative}")
            if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != entry["sha256"]:
                raise ValueError(f"Frozen migration changed or missing: {relative}. Restore it and add a new version for upgrades.")

        missing = []
        for app, schemas in APP_SCHEMAS.items():
            for schema in schemas:
                relative = f"{APP_DIRS[app]}/{target_name(schema)}"
                if relative not in frozen:
                    if (PAY_ROOT / relative).exists():
                        raise ValueError(f"Unregistered snapshot already exists: {relative}; refusing to overwrite or silently freeze it")
                    versions = [int(path.name[1:].split("__", 1)[0]) for path in (PAY_ROOT / APP_DIRS[app]).glob("V*.sql")]
                    if versions and int(SCHEMAS[schema][0]) <= max(versions):
                        raise ValueError(f"Snapshot version precedes existing history: {relative}. Add a reviewed migration with a newer version.")
                    missing.append((relative, schema))
        if args.check:
            for relative, _ in missing:
                print(f"Missing component snapshot: {relative}", file=sys.stderr)
            if missing:
                return 1
            print(f"Verified {len(frozen)} frozen component snapshots. Template upgrades require new migrations.")
            return 0

        pending = [(relative, schema, target_text(schema).encode("utf-8")) for relative, schema in missing]
        for relative, schema, content in pending:
            path = PAY_ROOT / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("xb") as output:
                output.write(content)
            frozen[relative] = {"sha256": hashlib.sha256(content).hexdigest(), "source": SCHEMAS[schema][1]}
        if pending:
            LOCK_PATH.write_text(json.dumps(lock, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        print(f"Created {len(pending)} initial component snapshots; existing migrations were preserved.")
        return 0
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Cannot generate component migrations: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
